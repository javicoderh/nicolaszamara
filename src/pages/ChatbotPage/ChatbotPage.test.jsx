import { act, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import ChatbotPage from './ChatbotPage.jsx'
import { mockChatApi, sessionResult } from '../../test/chatbotFixtures.js'

beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())

it('allows a draft during session recovery and waits for recovery plus 800 ms before sending', async () => {
  const api = mockChatApi()
  let resolve
  api.session.mockImplementation(() => new Promise((done) => { resolve = done }))
  render(<ChatbotPage api={api} />)
  expect(screen.getByRole('heading', { level: 1, name: '¿En qué podemos ayudarte?' })).toBeInTheDocument()
  expect(screen.getByText('Escríbenos tu consulta o elige una opción para conocer nuestros servicios.')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: /cerrar asistente|te ayudamos a elegir/i })).not.toBeInTheDocument()
  expect(screen.getByRole('status', { name: 'Preparando orientación' })).toBeInTheDocument()
  await act(async () => vi.advanceTimersByTimeAsync(2000))
  expect(screen.getByLabelText('Escribe tu consulta')).toBeEnabled()
  fireEvent.change(screen.getByLabelText('Escribe tu consulta'), { target: { value: 'Quiero conocer el curso' } })
  expect(screen.getByRole('button', { name: 'Enviar' })).toBeDisabled()
  expect(screen.getByLabelText('Escribe tu consulta')).toHaveAccessibleDescription(/conectando con el asistente/i)
  await act(async () => resolve(sessionResult()))
  await act(async () => vi.advanceTimersByTimeAsync(799))
  expect(screen.getByLabelText('Escribe tu consulta')).toHaveValue('Quiero conocer el curso')
  expect(screen.getByRole('button', { name: 'Enviar' })).toBeDisabled()
  await act(async () => vi.advanceTimersByTimeAsync(1))
  expect(screen.getByLabelText('Escribe tu consulta')).toBeEnabled()
  expect(screen.getByRole('button', { name: 'Enviar' })).toBeEnabled()
  expect(api.session).toHaveBeenCalledTimes(1)
  expect(screen.queryByRole('complementary')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Temas sugeridos')).not.toBeInTheDocument()
  expect(screen.getByRole('log', { name: 'Conversación' })).toBeEmptyDOMElement()
  const navigation = screen.getByRole('navigation', { name: 'Explorar servicios' })
  expect(within(navigation).getByRole('link', { name: 'Consulta' })).toHaveAttribute('href', '/consulta')
  expect(within(navigation).getByRole('link', { name: 'Curso online' })).toHaveAttribute('href', '/cursos#interes-online')
  expect(within(navigation).getAllByRole('link')).toHaveLength(6)
  expect(screen.getByLabelText('Escribe tu consulta').closest('form').compareDocumentPosition(navigation) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'Recuperar estado' })).not.toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Escribe tu consulta'), { target: { value: 'Quiero conocer el curso' } })
  fireEvent.click(screen.getByRole('button', { name: 'Enviar' }))
  await act(async () => vi.advanceTimersByTimeAsync(800))
  expect(api.send).toHaveBeenCalledTimes(1)
  expect(screen.getByRole('link', { name: /ver el curso e inscribirme/i })).toHaveAttribute('target', '_blank')
})

it('requests a fresh conversation and opens without the previous response', async () => {
  const previousReply = 'Para aprender más sobre Flores de Bach, Nicolás ofrece un curso.'
  const api = mockChatApi(sessionResult({ completed_rounds: 2, last_result: { reply: previousReply, request_id: 'previous-request' } }))
  render(<ChatbotPage api={api} />)
  await act(async () => vi.advanceTimersByTimeAsync(800))
  expect(screen.queryByText(previousReply)).not.toBeInTheDocument()
  expect(screen.getByRole('log', { name: 'Conversación' })).toBeEmptyDOMElement()
  expect(screen.getByLabelText('Escribe tu consulta')).toBeEnabled()
  expect(api.session).toHaveBeenCalledWith(expect.objectContaining({ fresh: true }))
  expect(api.command).not.toHaveBeenCalled()
  expect(api.send).not.toHaveBeenCalled()
})

it('shows a recoverable session failure after the delay', async () => {
  const api = mockChatApi()
  api.session.mockRejectedValue(new Error('storage_unavailable'))
  render(<ChatbotPage api={api} />)
  await act(async () => vi.advanceTimersByTimeAsync(799))
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  await act(async () => vi.advanceTimersByTimeAsync(1))
  expect(screen.getByRole('alert')).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Recuperar estado' })).toBeEnabled()
  fireEvent.change(screen.getByLabelText('Escribe tu consulta'), { target: { value: 'Mi consulta pendiente' } })
  expect(screen.getByLabelText('Escribe tu consulta')).toHaveValue('Mi consulta pendiente')
  expect(screen.getByRole('button', { name: 'Enviar' })).toBeDisabled()
  expect(screen.queryByRole('status', { name: 'Preparando orientación' })).not.toBeInTheDocument()
  expect(screen.getByLabelText('Escribe tu consulta')).toHaveAccessibleDescription(/tu mensaje no se ha enviado/i)
  api.session.mockResolvedValue(sessionResult())
  fireEvent.click(screen.getByRole('button', { name: 'Recuperar estado' }))
  await act(async () => vi.advanceTimersByTimeAsync(800))
  expect(screen.getByLabelText('Escribe tu consulta')).toHaveValue('Mi consulta pendiente')
  expect(screen.getByRole('button', { name: 'Enviar' })).toBeEnabled()
  fireEvent.click(screen.getByRole('button', { name: 'Enviar' }))
  await act(async () => vi.advanceTimersByTimeAsync(800))
  expect(api.send).toHaveBeenCalledTimes(1)
})
